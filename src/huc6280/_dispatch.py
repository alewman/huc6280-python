Entry = tuple[Callable[..., None], Callable[..., int] | None]


def build_table(cls: type) -> list[Entry]:
    """The 256 (handler, mode) pairs of ``cls``, as unbound functions."""
    table = []
    for opcode in range(256):
        handler, mode, *_ = OPCODES[opcode]
        table.append(
            (getattr(cls, f"_op_{handler}"), None if mode is None else getattr(cls, f"_ea_{mode}"))
        )
    return table
